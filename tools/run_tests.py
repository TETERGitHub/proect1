#!/usr/bin/env python3
"""Build the test bundle, run it with the Luau CLI and write docs/TESTING.md from the real output."""
import datetime
import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
import build  # noqa: E402

LUAU = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else pathlib.Path("/tmp/claude-0/luau/luau")
out = build.build(True)
proc = subprocess.run([str(LUAU), str(out)], capture_output=True, text=True)
text = proc.stdout
if "BEGIN_TABLE" not in text:
    print(proc.stdout)
    print(proc.stderr)
    sys.exit(1)
table = text.split("BEGIN_TABLE\n")[1].split("END_TABLE")[0]
total = [l for l in text.splitlines() if l.startswith("TOTAL")][-1]
version = subprocess.run([str(LUAU), "--help"], capture_output=True, text=True).stdout.splitlines()[:1]
stamp = datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
doc = f"""# Test results

Generated by `python3 tools/run_tests.py` from the real output of the standalone Luau runtime
(`luau` CLI, Roblox-API-free logic layer + mock Roblox layer). Run at {stamp}.

**{total}**

Rows marked PASS were executed in that run; nothing here is hand-written.
These tests do **not** prove behaviour inside a real Roblox client or a specific executor.

{table}
"""
(ROOT / "docs" / "TESTING.md").write_text(doc, encoding="utf-8")
print(total)
if proc.stderr.strip():
    print(proc.stderr)
sys.exit(0 if " FAILED 0" in total else 1)
