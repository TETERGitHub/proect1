#!/usr/bin/env python3
"""Pack assets/ui/*.png into src/data/UiPack.luau (base64). The hub writes them to MM2Hub/ui/ on first use (ui/Flair) and shows
them through getcustomasset; nothing is downloaded. Re-run after changing an image."""
import base64, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "assets" / "ui"
OUT = ROOT / "src" / "data" / "UiPack.luau"


def main():
    lines = ["--!nonstrict", "-- data/UiPack: GENERATED by tools/pack_ui.py from assets/ui (do not edit by hand).",
             "-- sticker.png, sticker_anim.png (8 frames, 4x2 grid of 128 px, laughing), sticker_mouth.png (10 frames, 5x2, mouth opening",
             "-- wider): the mascot, made from the Trollface drawing supplied by the",
             "-- project owner.", "", "return {"]
    for f in sorted(SRC.glob("*.png")):
        raw = f.read_bytes()
        lines.append('\t["%s"] = { bytes = %d, data = "%s" },' % (f.name, len(raw), base64.b64encode(raw).decode()))
    lines.append("}")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("packed", OUT)


if __name__ == "__main__":
    main()
