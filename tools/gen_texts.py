#!/usr/bin/env python3
"""Generate src/data/Texts_<lang>.luau from assets/i18n/<lang>.json (translations of the hub's interface texts).

  python3 tools/gen_texts.py            # every assets/i18n/*.json

assets/i18n/<lang>.json = {"exact": {English: text}, "patterns": [[lua pattern, template with %s], ...], "strings": {key: text},
"keep": [names shown unchanged]}. Russian lives in src/data/RuTexts.luau + data/Strings.luau and is the reference: the corpus for
new languages is extracted from it, so every language covers the same texts.
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "assets" / "i18n"


def lua(s):
    out = s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\r", "\\r").replace("\t", "\\t")
    return '"' + out + '"'


def generate(lang, data):
    lines = ["--!nonstrict", f"-- data/Texts_{lang}: GENERATED by tools/gen_texts.py from assets/i18n/{lang}.json (do not edit by hand).", ""]
    lines.append("local exact = {")
    for k in sorted(data["exact"]):
        lines.append(f"\t[{lua(k)}] = {lua(data['exact'][k])},")
    lines.append("}")
    lines.append("")
    lines.append("local patterns = {")
    for p, t in data["patterns"]:
        lines.append(f"\t{{ {lua(p)}, {lua(t)} }},")
    lines.append("}")
    lines.append("")
    lines.append("local keep = {")
    for k in data.get("keep", []):
        lines.append(f"\t[{lua(k)}] = true,")
    lines.append("}")
    lines.append("")
    lines.append("local strings = {")
    for k in sorted(data["strings"]):
        lines.append(f"\t[{lua(k)}] = {lua(data['strings'][k])},")
    lines.append("}")
    lines.append("")
    lines.append("return { exact = exact, patterns = patterns, keep = keep, strings = strings }")
    path = ROOT / "src" / "data" / f"Texts_{lang}.luau"
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return path


def main():
    for f in sorted(SRC.glob("*.json")):
        data = json.loads(f.read_text(encoding="utf-8"))
        p = generate(f.stem, data)
        print(f"{f.stem}: {len(data['exact'])} texts, {len(data['patterns'])} patterns, {len(data['strings'])} strings -> {p.name}")


if __name__ == "__main__":
    main()
