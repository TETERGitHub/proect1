#!/usr/bin/env python3
"""Bundle src/**/*.luau into a single executor-friendly script.

Usage: python3 tools/build.py [--tests]
  default : dist/MM2Hub.lua   (entry: main)
  --tests : dist/tests.lua    (tests/mock + src + tests, entry: tests/runner)
  --loader [--server-url URL] : dist/Loader.lua, the small client for server-licensed builds (docs/SERVER.md)
  --license : embed .license/secret.hex and require a valid key at startup (see docs/LICENSE.md)
Every module is wrapped as function(import) ... end and receives `import`
as its only argument (read in the module as `local import = ...`).
"""
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent


def collect(base: pathlib.Path, prefix: str = ""):
    mods = {}
    for path in sorted(base.rglob("*.luau")):
        name = prefix + path.relative_to(base).with_suffix("").as_posix()
        mods[name] = path.read_text(encoding="utf-8")
    return mods


HEADER = """-- MM2 Hub bundle (generated by tools/build.py; edit src/, not this file)
local __modules = {}
local __cache = {}
local __loading = {}
local function __import(name)
	local cached = __cache[name]
	if cached ~= nil then
		return cached
	end
	local fn = __modules[name]
	if not fn then
		error("module not found: " .. tostring(name), 2)
	end
	if __loading[name] then
		error("circular import: " .. name, 2)
	end
	__loading[name] = true
	-- a failing module must not stay marked as loading, or a retry would report a bogus circular import
	local ok, result = pcall(fn, __import)
	__loading[name] = nil
	if not ok then
		error(result, 0)
	end
	if result == nil then
		result = true
	end
	__cache[name] = result
	return result
end
"""


def build(with_tests: bool, license_secret_hex: str = "", require_license: bool = False) -> pathlib.Path:
    mods = collect(ROOT / "src")
    if license_secret_hex:
        lic = mods["core/License"]
        mods["core/License"] = lic.replace("@@LICENSE_SECRET_HEX@@", license_secret_hex).replace(
            "@@LICENSE_REQUIRED@@", "1" if require_license else "0")
    parts = []
    if with_tests:
        mock = (ROOT / "tests" / "mock.luau").read_text(encoding="utf-8")
        parts.append("-- ===== tests/mock =====\n" + mock + "\n")
        mods.update(collect(ROOT / "tests", "tests/"))
        mods.pop("tests/mock", None)
        mods.update(collect(ROOT / "loader", "loader/"))
        mods.pop("loader/main", None)
    parts.append(HEADER)
    for name, src in mods.items():
        parts.append(f'__modules["{name}"] = function(...)\nlocal __args = ...\n{src}\nend\n')
    entry = "tests/runner" if with_tests else "main"
    parts.append(f'return __import("{entry}")\n')
    out_dir = ROOT / "dist"
    out_dir.mkdir(exist_ok=True)
    out = out_dir / ("tests.lua" if with_tests else "MM2Hub.lua")
    out.write_text("\n".join(parts), encoding="utf-8")
    return out


def build_loader(server_url: str) -> pathlib.Path:
    """dist/Loader.lua: the small licensed-build client (no signing secret, no hub code)."""
    wanted = ["core/Hash", "core/Codec", "core/Json", "core/PayloadCipher", "core/LicenseText", "ui/KeyCard", "data/UiPack"]
    mods = {name: src for name, src in collect(ROOT / "src").items() if name in wanted}
    loader = collect(ROOT / "loader", "loader/")
    mods["loader/Loader"] = loader["loader/Loader"]
    mods["main"] = loader["loader/main"].replace("@@SERVER_URL@@", server_url)
    parts = [HEADER]
    for name, src in mods.items():
        parts.append(f'__modules["{name}"] = function(...)\nlocal __args = ...\n{src}\nend\n')
    parts.append('return __import("main")\n')
    out = ROOT / "dist" / "Loader.lua"
    out.write_text("\n".join(parts), encoding="utf-8")
    return out


if __name__ == "__main__":
    if "--loader" in sys.argv:
        url = sys.argv[sys.argv.index("--server-url") + 1] if "--server-url" in sys.argv else "https://YOUR-SERVER.example"
        path = build_loader(url)
        print(f"wrote {path} ({path.stat().st_size} bytes), server {url}")
        sys.exit(0)
    secret, required = "", False
    if "--license" in sys.argv:
        secret_file = ROOT / ".license" / "secret.hex"
        if not secret_file.exists():
            sys.exit("No secret. Run: python3 tools/keygen.py init")
        secret = secret_file.read_text().strip()
        required = True
        print("NOTE: the licence secret is embedded in dist/MM2Hub.lua - never publish that file's source if keys must stay unforgeable.")
    path = build("--tests" in sys.argv, secret, required)
    print(f"wrote {path} ({path.stat().st_size} bytes)")
