#!/usr/bin/env python3
"""Generate docs/AUDIT.md: file registry, feature registry, settings wiring and the page-by-page button table.

Everything except the hand-written notes at the bottom is derived from the sources and from a real run:
  python3 tools/audit_registry.py [path-to-luau]
The button table comes from tests/audit_dump.luau (boots the hub on the mock, presses every button once)."""
import collections
import json
import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
import build  # noqa: E402

LUAU = sys.argv[1] if len(sys.argv) > 1 else "/tmp/claude-0/luau/luau"

GROUPS = [
    ("Core and module lifecycle", ["src/core/Core", "src/core/Registry", "src/core/Services", "src/core/Maid", "src/core/Signal", "src/core/Perf", "src/core/Actions", "src/core/Logger", "src/core/Env", "src/core/Pool", "src/core/Diagnostics", "src/core/Version", "src/core/Recents", "src/core/Search", "src/core/Notify", "src/core/Input"]),
    ("Settings, schema and configs", ["src/core/Settings", "src/data/Schema", "src/core/Config", "src/data/Features", "src/data/Themes"]),
    ("Localisation", ["src/core/I18n", "src/data/Strings", "src/data/RuTexts"]),
    ("UI, windows, pages", ["src/ui/"]),
    ("Features (game-side behaviour, local only)", ["src/features/"]),
    ("Licensing and crypto primitives", ["src/core/License", "src/core/LicenseText", "src/core/Hash", "src/core/Codec", "src/core/Json", "src/core/PayloadCipher"]),
    ("Loader (client of the licence server)", ["loader/"]),
    ("Application root", ["src/app/", "src/main"]),
    ("Server", ["server/app.py", "server/licensing.py"]),
    ("Build, tooling, generation", ["tools/"]),
    ("Tests", ["tests/", "server/tests/"]),
    ("Documentation", ["docs/", "README.md"]),
]


def group_of(path: str) -> str:
    for name, prefixes in GROUPS:
        for p in prefixes:
            if path.startswith(p) or path.startswith(p + "."):
                return name
    return "Other"


def purpose(path: pathlib.Path) -> str:
    try:
        lines = path.read_text(encoding="utf-8").splitlines()[:6]
    except Exception:
        return ""
    for l in lines:
        m = re.match(r"^(?:--|#)\s*(?!!)(.*)", l) or re.match(r'^"""(.*)', l)
        if m and m.group(1).strip():
            return m.group(1).strip().replace("|", "/")[:150]
    return ""


def main():
    tests = {p: p.read_text(encoding="utf-8") for p in (ROOT / "tests").glob("*.luau") if not p.name.startswith(("audit_", "i18n_probe", "mock"))}
    tests.update({p: p.read_text(encoding="utf-8") for p in (ROOT / "server" / "tests").glob("*.py")})
    sources = {p: p.read_text(encoding="utf-8") for p in list((ROOT / "src").rglob("*.luau")) + list((ROOT / "loader").glob("*.luau"))}
    # modules that a test run actually loads: everything statically imported (transitively) by a module a test imports
    src_mods = {}
    for p_, t_ in sources.items():
        rel_ = p_.relative_to(ROOT).as_posix()
        name_ = rel_[4:-5] if rel_.startswith("src/") else rel_[:-5]
        src_mods[name_] = t_
    loaded = set()
    todo = [m for body in tests.values() for m in re.findall(r'import\("([^"]+)"\)', body)]
    while todo:
        m = todo.pop()
        if m in loaded or m not in src_mods:
            continue
        loaded.add(m)
        todo += re.findall(r'import\("([^"]+)"\)', src_mods[m])
    out = ["# Audit registry (generated)", "",
           "Generated by `python3 tools/audit_registry.py`. Counts, imports and test references are computed from the files; "
           "the notes at the end are hand-written and say what is NOT verified.", ""]

    # 1. file registry ---------------------------------------------------------------------------------------------
    out += ["## 1. File registry", "", "`Tests` = test files that import the module or mention its name. Nothing here was run in a real Roblox client.", ""]
    files = sorted(p for p in ROOT.rglob("*") if p.is_file() and not any(x in p.parts for x in (".git", "dist", "__pycache__", ".license")) and p.suffix in (".luau", ".py", ".md", ".bat", ".sh"))
    by = collections.defaultdict(list)
    for p in files:
        by[group_of(p.relative_to(ROOT).as_posix())].append(p)
    for name, _ in GROUPS + [("Other", [])]:
        if not by.get(name):
            continue
        out += [f"### {name}", "", "| File | Lines | Purpose | Imports | Tests |", "|---|---|---|---|---|"]
        for p in by[name]:
            rel = p.relative_to(ROOT).as_posix()
            text = p.read_text(encoding="utf-8", errors="replace")
            imports = sorted(set(re.findall(r'import\("([^"]+)"\)', text)))
            mod = rel[4:-5] if rel.startswith("src/") and rel.endswith(".luau") else (rel[:-5] if rel.startswith("loader/") else None)
            base = pathlib.Path(rel).stem
            refs = []
            if mod:
                refs = sorted(t.name for t, body in tests.items() if f'import("{mod}")' in body or re.search(r"\b%s\b" % re.escape(base), body))
                if not refs and mod in loaded:
                    refs = ["(indirect: loaded by tests through its importers)"]
            elif rel.endswith(".py") and not rel.startswith("server/tests"):
                refs = sorted(t.name for t, body in tests.items() if re.search(r"\b%s\b" % re.escape(base), body))
            imp = ", ".join(imports[:6]) + (f" (+{len(imports) - 6})" if len(imports) > 6 else "")
            out.append(f"| `{rel}` | {len(text.splitlines())} | {purpose(p)} | {imp or '-'} | {(', '.join(refs[:4]) + (' ...' if len(refs) > 4 else '')) or ('n/a' if rel.startswith(('tests/', 'docs/', 'README', 'server/tests/')) else '**none**')} |")
        out.append("")

    # 2. feature registry ------------------------------------------------------------------------------------------
    feat = (ROOT / "src/data/Features.luau").read_text(encoding="utf-8")
    rows = re.findall(r'^F\("([^"]+)",\s*"(\w)",\s*"([^"]*)",\s*"[^"]*",\s*"(\w+)",\s*"([^"]*)",\s*"([^"]*)"(?:,\s*"([^"]*)")?\)', feat, re.M)
    alltests = "\n".join(tests.values())
    out += ["## 2. Feature registry", "", f"{len(rows)} entries parsed from `src/data/Features.luau`.", "",
            "| Id | Feature | Status | Bound to | Tests mention the binding | Limitation |", "|---|---|---|---|---|---|"]
    counts = collections.Counter()
    for fid, cat, name, status, binding, desc, note in rows:
        counts[status] += 1
        kind, _, target = binding.partition(":")
        needle = target.split(":")[0] if kind in ("s", "a", "u", "f") else target
        needle = needle.split("/")[-1] if kind == "f" else needle
        hit = bool(needle) and needle in alltests
        out.append(f"| {fid} | {name} | {status} | `{binding}` | {'yes' if hit else '**no**'} | {note or ''} |".replace("|  |", "| |"))
    out += ["", "Status counts: " + ", ".join(f"{k}={v}" for k, v in sorted(counts.items())), ""]

    # 3. settings wiring -------------------------------------------------------------------------------------------
    schema = (ROOT / "src/data/Schema.luau").read_text(encoding="utf-8")
    ids = re.findall(r'^\t(bool|num|enum|color|key|text|str|list)\w*\("([\w.]+)"', schema, re.M)
    logic = "\n".join(t for p, t in sources.items() if "/ui/" not in p.as_posix() and p.name not in ("Schema.luau", "Strings.luau", "RuTexts.luau") and not p.name.startswith("Pages"))
    ui = "\n".join(t for p, t in sources.items() if "/ui/" in p.as_posix())
    out += ["## 3. Settings wiring", "", f"{len(ids)} schema entries. `Consumed by` = a non-UI module reads it (literal key or prefix pattern); `UI` = a page or window code references it; `Tests` = a test mentions it.", "",
            "| Setting | Kind | Consumed by logic | UI | Tests |", "|---|---|---|---|---|"]
    for kind, key in ids:
        pre, leaf = key.rsplit(".", 1)
        consumers = sorted({p.stem for p, t in sources.items() if "/ui/" not in p.as_posix() and not p.name.startswith("Pages") and p.name not in ("Schema.luau", "Strings.luau", "RuTexts.luau") and (f'"{key}"' in t or (f'"{pre}."' in t and re.search(r'["\']%s["\']' % re.escape(leaf), t)))})
        in_ui = f'"{key}"' in ui or (f'"{pre}."' in ui and re.search(r'["\']%s["\']' % re.escape(leaf), ui)) is not None
        tested = key in alltests or (f'"{pre}."' in alltests and leaf in alltests)
        cons = ", ".join(consumers) if consumers else ("UI only" if in_ui else "**nobody**")
        out.append(f"| `{key}` | {kind} | {cons} | {'yes' if in_ui else 'no'} | {'yes' if tested else '**no**'} |")
    out.append("")

    # 4. button table ----------------------------------------------------------------------------------------------
    dump = ROOT / "dist" / "audit_dump.json"
    if "--no-run" not in sys.argv:
        t = build.build(True).read_text(encoding="utf-8").replace('return __import("tests/runner")', 'return __import("tests/audit_dump")')
        q = ROOT / "dist" / "audit.lua"
        q.write_text(t, encoding="utf-8")
        res = subprocess.run([LUAU, str(q)], capture_output=True, text=True, timeout=1800)
        line = [l for l in res.stdout.splitlines() if l.startswith("@@")]
        if not line:
            sys.exit("audit dump failed:\n" + res.stdout[-2000:] + res.stderr[-2000:])
        dump.write_text(line[-1][2:], encoding="utf-8")
    data = json.loads(dump.read_text(encoding="utf-8"))
    rows = data["rows"]
    eff = collections.Counter(r["effect"].split()[0] for r in rows)
    out += ["## 4. Buttons -> effect (measured on the mock)", "",
            f"{len(rows)} buttons pressed once each, in page order; effect = what the press observably did. Totals: " + ", ".join(f"{k}={v}" for k, v in sorted(eff.items())) + ".", "",
            "`NONE` means the press changed no setting, ran no action, raised no notification, did not navigate and did not change the widget tree. "
            "That is expected for some controls (a button that only re-renders a value already shown) and a defect for others; each NONE row is judged in the notes.", "",
            "| Page | Button | Effect |", "|---|---|---|"]
    for r in rows:
        txt = (r["text"] or r["name"]).replace("|", "/")[:40]
        out.append(f"| {r['page']} | {txt} | {r['effect'].replace('|', '/')[:90]} |")
    out.append("")
    out += ["## 5. Settings controls found on each page (measured)", "", "| Page | Controls named after a setting key |", "|---|---|"]
    for page, keys in data["pageKeys"].items():
        out.append(f"| {page} | {', '.join('`' + k + '`' for k in keys) or '-'} |")
    out.append("")
    notes = ROOT / "docs" / "AUDIT_NOTES.md"
    if notes.exists():
        out += [notes.read_text(encoding="utf-8")]
    (ROOT / "docs" / "AUDIT.md").write_text("\n".join(out), encoding="utf-8")
    print("wrote docs/AUDIT.md", len(out), "lines")


if __name__ == "__main__":
    main()
