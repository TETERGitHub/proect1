#!/usr/bin/env python3
"""Pack assets/sounds/*.mp3 into src/data/SoundPack.luau (base64 strings + measured durations).

The hub writes these files to MM2Hub/sounds/ on first use (features/SoundPack), so a bundled sound needs no manual copying. Durations come
from ffprobe, i.e. they are measured, not guessed. Re-run after adding a file and listing it in assets/sounds/sounds.json.
"""
import base64, json, pathlib, subprocess, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "assets" / "sounds"
OUT = ROOT / "src" / "data" / "SoundPack.luau"


def duration(path):
    r = subprocess.run(["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", str(path)], capture_output=True, text=True)
    try:
        return round(float(r.stdout.strip().split(",")[0]), 3)
    except ValueError:
        return 0.0


def main():
    manifest = json.loads((SRC / "sounds.json").read_text(encoding="utf-8"))
    lines = [
        "--!nonstrict",
        "-- data/SoundPack: GENERATED by tools/pack_sounds.py from assets/sounds (do not edit by hand).",
        "-- Sound files supplied by the project owner, base64 encoded, with measured durations.",
        "",
        "return {",
    ]
    total = 0
    for s in manifest["sounds"]:
        raw = (SRC / s["file"]).read_bytes()
        total += len(raw)
        lines.append("\t{ file = %s, name = %s, ru = %s, category = %s, bytes = %d, duration = %s,\n\t\tdata = \"%s\" }," % (
            json.dumps(s["file"]), json.dumps(s["name"]), json.dumps(s["ru"], ensure_ascii=False), json.dumps(s["category"]),
            len(raw), duration(SRC / s["file"]), base64.b64encode(raw).decode()))
    lines.append("}")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("packed %d sounds, %d bytes -> %s" % (len(manifest["sounds"]), total, OUT))


if __name__ == "__main__":
    main()
